// Engine adapter: the only code that knows about Liquidsoap and Icecast.
// Each station runs in its own Liquidsoap container, so starting, changing or
// crashing one station never touches another station's listeners.
// Icecast is shared (engine/docker-compose.yml); a station only owns its mount.
import { execFile } from 'node:child_process';
import { mkdirSync, writeFileSync, copyFileSync, rmSync, readFileSync, existsSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import net from 'node:net';

const ENGINE_DIR = resolve(import.meta.dirname, '../../../engine');
const MEDIA_DIR = join(ENGINE_DIR, 'media');
const GENERATED_DIR = join(ENGINE_DIR, 'generated');
const IMAGE = 'savonet/liquidsoap:v2.3.2';
const NETWORK = process.env.VG_ENGINE_NETWORK ?? 'voxgarden-engine';
const LABEL = 'voxgarden.station';
// Liquidsoap needs far more memory while compiling its script at start-up than
// when running, so the cap is set for the start-up peak (see docs/ENGINE-SPIKE.md).
const MEMORY_LIMIT = process.env.VG_STATION_MEMORY ?? '512m';

export interface EngineStation {
  id: number;
  slug: string;
  name: string;
  bitrate: number;
  harbor_password: string;
}

// Engine secrets live in engine/.env (git-ignored), shared with the Icecast container.
function engineEnv(): Record<string, string> {
  const file = join(ENGINE_DIR, '.env');
  const out: Record<string, string> = {};
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const m = /^([A-Z_]+)=(.*)$/.exec(line.trim());
    if (m) out[m[1]] = m[2];
  }
  return out;
}

// Ports on 127.0.0.1 only: telnet is how the control platform drives a station,
// harbor is the live input (Go Live will reach it through the control platform).
export const telnetPort = (id: number) => 20000 + id;
export const livePort = (id: number) => 21000 + id;
const containerName = (slug: string) => `vg-station-${slug}`;

export function mediaDir(slug: string): string {
  const dir = join(MEDIA_DIR, slug);
  mkdirSync(dir, { recursive: true });
  return dir;
}

// Liquidsoap strings: keep user text out of code by escaping.
const q = (s: string) => JSON.stringify(s);

// Priority per station: live presenter > scheduled item > AutoDJ rotation.
export function renderConfig(s: EngineStation): string {
  return `# Generated by the VoxGarden control platform. Do not edit.
settings.log.stdout := true
settings.log.level := 3
settings.server.telnet := true
settings.server.telnet.bind_addr := "0.0.0.0"
settings.harbor.bind_addrs := ["0.0.0.0"]

pw = environment.get("ICECAST_SOURCE_PASSWORD")
live_pw = environment.get("HARBOR_PASSWORD")

auto = mksafe(playlist(id="auto", mode="randomize", reload_mode="watch", ${q('/media/' + s.slug)}))
sched = request.queue(id="sched")
live = input.harbor(id="live", "live", port=8005, password=live_pw, buffer=2., max=10.)

radio = fallback(id="radio", track_sensitive=false, [live, sched, auto])
radio.on_track(fun (m) -> log.important(label="onair", 'ONAIR rid=#{m["rid"]} t=#{time()}'))

output.icecast(%mp3(bitrate=${s.bitrate}), host="icecast", port=8000, password=pw,
  mount=${q('/' + s.slug)}, name=${q(s.name)}, description="VoxGarden station", radio)
`;
}

function docker(args: string[], env: Record<string, string> = {}): Promise<{ ok: boolean; out: string }> {
  return new Promise((done) => {
    execFile('docker', args, { env: { ...process.env, ...env } }, (err, stdout, stderr) => {
      done({ ok: !err, out: (stdout || stderr || err?.message || '').trim() });
    });
  });
}

// One operation at a time per station, so two uploads can't race to start it twice.
const locks = new Map<string, Promise<unknown>>();
function serial<T>(slug: string, fn: () => Promise<T>): Promise<T> {
  const next = (locks.get(slug) ?? Promise.resolve()).then(fn, fn);
  locks.set(slug, next.catch(() => {}));
  return next;
}

// Writes the station's config and makes sure its process is running with it.
// Only this station's process is (re)started; other stations are untouched.
export function ensureRunning(s: EngineStation): Promise<void> {
  return serial(s.slug, async () => {
    mkdirSync(GENERATED_DIR, { recursive: true });
    mediaDir(s.slug);
    const file = join(GENERATED_DIR, `${s.slug}.liq`);
    const config = renderConfig(s);
    const changed = !existsSync(file) || readFileSync(file, 'utf8') !== config;
    if (changed) writeFileSync(file, config);

    const state = await docker(['inspect', '-f', '{{.State.Running}}', containerName(s.slug)]);
    if (state.ok && state.out === 'true') {
      if (changed) await docker(['restart', containerName(s.slug)]);
      return;
    }
    if (state.ok) await docker(['rm', '-f', containerName(s.slug)]); // stopped or crashed: recreate

    const { ICECAST_SOURCE_PASSWORD = '' } = engineEnv();
    const run = await docker([
      'run', '-d', '--name', containerName(s.slug), '--label', `${LABEL}=${s.slug}`,
      '--network', NETWORK, '--restart', 'unless-stopped', '--memory', MEMORY_LIMIT,
      // Values come from the env below, so secrets never appear in the process list.
      '-e', 'ICECAST_SOURCE_PASSWORD', '-e', 'HARBOR_PASSWORD',
      '-v', `${file}:/etc/liquidsoap/station.liq:ro`,
      '-v', `${mediaDir(s.slug)}:/media/${s.slug}:ro`,
      '-p', `127.0.0.1:${telnetPort(s.id)}:1234`,
      '-p', `127.0.0.1:${livePort(s.id)}:8005`,
      IMAGE, '/etc/liquidsoap/station.liq',
    ], { ICECAST_SOURCE_PASSWORD, HARBOR_PASSWORD: s.harbor_password });
    if (!run.ok) console.warn(`engine: could not start ${s.slug}: ${run.out}`);
  });
}

export function stopStation(slug: string): Promise<void> {
  return serial(slug, async () => { await docker(['rm', '-f', containerName(slug)]); });
}

// On boot: run every station that should be on air, and remove containers for
// stations that no longer exist.
export async function reconcile(onAir: EngineStation[], allSlugs: string[]): Promise<void> {
  const known = new Set(allSlugs);
  const listed = await docker(['ps', '-a', '--filter', `label=${LABEL}`, '--format', `{{.Label "${LABEL}"}}`]);
  for (const slug of listed.ok ? listed.out.split('\n').filter(Boolean) : []) {
    if (!known.has(slug)) await stopStation(slug);
  }
  // Stagger start-ups so several stations don't hit their memory peak at once.
  for (const s of onAir) {
    await ensureRunning(s);
    await new Promise((r) => setTimeout(r, 4000));
  }
}

// Sends one telnet command to a station's Liquidsoap and returns its reply.
export function command(stationId: number, cmd: string, timeoutMs = 3000): Promise<string> {
  return new Promise((ok, fail) => {
    const sock = net.connect(telnetPort(stationId), '127.0.0.1');
    let buf = '';
    let done = false;
    const finish = (fn: () => void) => { if (!done) { done = true; sock.destroy(); fn(); } };
    sock.setTimeout(timeoutMs, () => finish(() => fail(new Error('engine did not answer'))));
    sock.on('data', (d) => {
      buf += d;
      if (buf.includes('\nEND')) finish(() => ok(buf.split('\nEND')[0].trim()));
    });
    sock.on('error', (e) => finish(() => fail(e)));
    sock.write(cmd.replace(/[\r\n]/g, '') + '\n');
  });
}

// Puts a library file on air now. It interrupts AutoDJ, and with hardStart it also
// cuts off a scheduled item that is still playing, so every slot starts on time.
// (The queue only ever holds items whose time has come, so flushing is safe.)
// Returns Liquidsoap's request id.
export async function playNow(s: { id: number; slug: string }, filename: string, hardStart = true): Promise<string> {
  if (!/^[a-zA-Z0-9._-]+$/.test(filename)) throw new Error('bad filename');
  if (!existsSync(join(MEDIA_DIR, s.slug, filename))) throw new Error('file missing from library');
  if (hardStart) await command(s.id, 'sched.flush_and_skip');
  const reply = await command(s.id, `sched.push /media/${s.slug}/${filename}`);
  const rid = reply.split('\n').pop() ?? '';
  if (!/^\d+$/.test(rid)) throw new Error(`engine refused: ${reply.slice(0, 80)}`);
  return rid;
}

// ---- recordings (FR-04): trim and convert with the same Liquidsoap image ----
// One conversion at a time: Liquidsoap briefly needs ~300 MB while starting.
let convertQueue: Promise<unknown> = Promise.resolve();

// Cuts [start, end] seconds out of a phone recording and converts it to a 64 kbps
// mono MP3 (about 29 MB per hour), running unsynced so it takes seconds, not real time.
// workDir must contain `in.<ext>`; the result is written to workDir/out.mp3.
//
// Browser recordings (MediaRecorder WebM/Ogg) have no seek index, so Liquidsoap
// can't jump to a start point in them ("Initial seek mismatch") and would silently
// keep the beginning. When the start is trimmed, pass 1 decodes up to `end` into a
// WAV (no seeking needed), and pass 2 cuts the start from that WAV, which can seek.
export function convertRecording(workDir: string, ext: string, start: number, end: number): Promise<string> {
  const job = async () => {
    if (!/^(webm|ogg|m4a|wav|mp3)$/.test(ext)) throw new Error('unsupported format');
    const cut = (n: number) => n.toFixed(3); // numbers only: nothing from the user reaches the scripts as text
    const pass = (input: string, cues: string, output: string, format: string) => `settings.log.stdout := true
settings.log.level := 2
s = once(single("annotate:${cues}:/work/${input}"))
clock.assign_new(sync="none", [s])
output.file(${format}, "/work/${output}", fallible=true, on_stop=shutdown, s)
`;
    const mp3 = '%mp3(mono, bitrate=64)';
    const trimStart = start >= 0.05;
    if (trimStart) {
      writeFileSync(join(workDir, 'pass1.liq'), pass(`in.${ext}`, `liq_cue_out=${cut(end)}`, 'full.wav', '%wav(mono)'));
      writeFileSync(join(workDir, 'pass2.liq'), pass('full.wav', `liq_cue_in=${cut(start)}`, 'out.mp3', mp3));
    } else {
      writeFileSync(join(workDir, 'pass2.liq'), pass(`in.${ext}`, `liq_cue_out=${cut(end)}`, 'out.mp3', mp3));
    }
    const steps = trimStart ? 'liquidsoap /work/pass1.liq && liquidsoap /work/pass2.liq' : 'liquidsoap /work/pass2.liq';

    const name = `vg-convert-${Date.now().toString(36)}`;
    // Run as this user so the output file is ours (and readable on Linux hosts).
    const user = typeof process.getuid === 'function' ? ['--user', `${process.getuid()}:${process.getgid?.()}`] : [];
    // Generous limit: a 10-minute recording takes ~10 s per pass.
    const timer = setTimeout(() => { docker(['rm', '-f', name]); }, 60_000 + (end - start) * 200);
    try {
      await docker(['run', '--rm', '--name', name, '--network', 'none', '--memory', MEMORY_LIMIT, ...user,
        '-e', 'HOME=/tmp', '-v', `${workDir}:/work`, '--entrypoint', 'sh', IMAGE, '-c', steps]);
    } finally {
      clearTimeout(timer);
    }
    const out = join(workDir, 'out.mp3');
    if (!existsSync(out) || statSync(out).size < 1000) throw new Error('Could not read that recording. Try recording again.');
    return out;
  };
  const run = convertQueue.then(job, job);
  convertQueue = run.catch(() => {});
  return run;
}

export function importTrack(slug: string, srcPath: string, filename: string): string {
  let safe = filename.replace(/[^a-zA-Z0-9._-]/g, '_');
  // Never overwrite an existing track that the library or schedule may point at.
  if (existsSync(join(mediaDir(slug), safe))) safe = `${Date.now().toString(36)}-${safe}`;
  copyFileSync(srcPath, join(mediaDir(slug), safe));
  return safe;
}

export function removeTrack(slug: string, filename: string): void {
  rmSync(join(mediaDir(slug), filename), { force: true });
}

// Where listeners reach Icecast. In production this is the public stream host.
const STREAM_BASE = (process.env.VG_STREAM_BASE ?? 'http://localhost:8000').replace(/\/$/, '');
// Where the control platform reaches Icecast itself (status, listener counts).
const ICECAST_INTERNAL = process.env.VG_ICECAST_INTERNAL ?? 'http://127.0.0.1:8000';

export function listenUrl(slug: string): string {
  return `${STREAM_BASE}/${slug}`;
}

export const streamOrigin = () => new URL(STREAM_BASE).origin;

// Which mounts are live and how many listeners each has, from Icecast's status
// page. Cached briefly so a busy public page doesn't hammer Icecast.
let statusCache: { at: number; mounts: Map<string, number> } | null = null;
export async function mountStatus(): Promise<Map<string, number>> {
  if (statusCache && Date.now() - statusCache.at < 5_000) return statusCache.mounts;
  const mounts = new Map<string, number>();
  try {
    const res = await fetch(`${ICECAST_INTERNAL}/status-json.xsl`, { signal: AbortSignal.timeout(2_000) });
    const src = (await res.json())?.icestats?.source ?? [];
    for (const s of Array.isArray(src) ? src : [src]) {
      const mount = new URL(s.listenurl).pathname.slice(1);
      mounts.set(mount, Number(s.listeners) || 0);
    }
  } catch {
    // Icecast unreachable: report every station off air rather than failing the page.
  }
  statusCache = { at: Date.now(), mounts };
  return mounts;
}
